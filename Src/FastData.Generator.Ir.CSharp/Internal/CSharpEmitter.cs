using Genbox.FastData.Generator.Ir.Emission;
using Genbox.FastData.Generator.Ir.Operations;
using Genbox.FastData.Generator.Ir.Prepared;
using Genbox.FastData.Ir.Model;
using Genbox.FastData.Ir.Model.Abstracts;
using Genbox.FastData.Ir.Model.Enums;
using static Genbox.FastData.Generator.Ir.Emission.SourceWriter;

namespace Genbox.FastData.Generator.Ir.CSharp.Internal;

internal sealed class CSharpEmitter(CSharpIrCodeGeneratorConfig config, EmissionContext context) : IrSourceEmitter(context, new CSharpLiterals(context.Lookup.Records, context.Lookup.Encoding, context.Plan.Reference))
{
    private readonly CSharpText _text = new CSharpText(context.Lookup.Encoding);

    protected override IrSourceEmitter CreateEmitter(EmissionContext context) => new CSharpEmitter(config, context);

    protected override string EmitSource() =>
        $$"""
          // <auto-generated />
          // This file is auto-generated from the FastData portable IR. Do not edit manually.
          // Structure: {{Lookup.StructureName}}
          #nullable enable
          using System;
          using System.Collections.Generic;
          using System.Numerics;
          using System.Runtime.CompilerServices;
          using System.Runtime.InteropServices;

          {{(config.Namespace is {} ns ? $"namespace {ns};" : "")}}

          internal static class {{config.ClassName}}
          {
          {{JoinLines(Lookup.Records.Select(Record), 1)}}
          {{DataDeclarations(1)}}
          {{Indent(PublicApi())}}
          {{FunctionDeclarations(1)}}
          {{JoinLines(_text.Helpers(Lookup.RequiredBuiltins), 1)}}
          }
          """;

    private string Record(PreparedRecord record) =>
        $$"""
          public sealed class {{record.Name}}
          {
          {{JoinLines(record.Record.Fields.Select((field, i) => $"public readonly {Type(field.Type)} {record.FieldNames[i]};"), 1)}}

              public {{record.Name}}({{string.Join(", ", record.Record.Fields.Select((field, i) => Parameter(record.FieldNames[i], field.Type)))}})
              {
          {{JoinLines(record.FieldNames.Select(name => $"this.{name} = {name};"), 2)}}
              }
          }
          """;

    protected override string Data(PreparedData data)
    {
        string visibility = data.Exported ? "public" : "private";
        string modifier = data.Exported && CSharpLiterals.IsConstant(data.Value, Lookup.Encoding) ? "const" : "static readonly";
        string declaration = $"{visibility} {modifier} {Type(data.Type)} {data.Name}";

        if (data.Value is IrArrayLiteralBase { Count: > 8 } array)
        {
            return $$"""
                     {{declaration}} = new {{Type(array.ElementType)}}[]
                     {
                     {{Elements(array)}}
                     };
                     """;
        }

        return $"{declaration} = {Initializer(data.Value)};";
    }

    protected override string Local(string name, IrType type) => $"{Type(type)} {name} = default!;";

    protected override string Function(string name, IrType returnType, string parameters, string body) =>
        $$"""
          [MethodImpl(MethodImplOptions.AggressiveInlining)]
          private static {{Type(returnType)}} {{name}}({{parameters}})
          {
              unchecked
              {
          {{Indent(body, 2)}}
              }
          }
          """;

    protected override string Contains(RenderedLookupApi api) =>
        $"""
         [MethodImpl(MethodImplOptions.AggressiveInlining)]
         public static bool Contains({api.KeyType} key) => {api.Contains};
         """;

    protected override string TryLookup(RenderedLookupApi api, RenderedLookupValue value) =>
        $$"""
          public static bool TryLookup({{api.KeyType}} key, out {{value.Type}} value)
          {
              int slot = {{api.Find}};
              if ({{api.Found}})
              {
                  value = {{value.Expression}};
                  return true;
              }

              value = default!;
              return false;
          }
          """;

    protected override string Slice(bool keys, RenderedLookupValue slice) => $"public static ReadOnlySpan<{slice.Type}> {(keys ? "KeySpan" : "ValueSpan")} => {slice.Expression};";

    protected override string Enumeration(RenderedEnumeration enumeration) =>
        $$"""
          public static IEnumerable<{{enumeration.Type}}> {{enumeration.Name}}
          {
              get
              {
                  for (long position = {{enumeration.Start}}; {{enumeration.HasCurrent}}; position = {{enumeration.Advance}})
                      yield return {{enumeration.Current}};
              }
          }
          """;

    protected override void WriteStatements(SourceWriter writer, IrBlock block, IReadOnlyList<string> variables, Func<IrExpression, string> expression)
    {
        SwitchDetectionVisitor dispatch = new SwitchDetectionVisitor(variables);

        for (int i = 0; i < block.Statements.Count; i++)
        {
            dispatch.Visit(block, i);

            if (dispatch.VariableName is not {} name || (dispatch.Type == IrType.String && !_text.IsUtf16))
            {
                WriteStatement(writer, block.Statements[i], variables, expression);
                continue;
            }

            writer.Line($"switch ({name})");
            writer.Open();
            foreach ((IrLiteral label, IrExpression result) in dispatch.Cases)
                writer.Line($"case {expression(label)}: return {expression(result)};");
            writer.Close();
            i += dispatch.Cases.Count - 1;
        }
    }

    protected override string IndexAccess(string collection, string index) => $"({collection})[{index}]";
    protected override string FieldAccess(string receiver, IrFieldId field) => $"({receiver}!).{Lookup.FieldName(field)}";
    protected override string NullCheck(string operand, bool isNull) => $"({operand} {(isNull ? "==" : "!=")} null)";
    protected override string Builtin(IrBuiltinOperation operation, string[] arguments) => CSharpRuntime.Call(operation, arguments);

    protected override string FormatExpression(IrExpression expression, Func<IrExpression, string> render) => expression switch
    {
        IrConversionExpression { Conversion: ConversionKind.BitCast } cast => CSharpRuntime.BitCast(cast.Operand.Type, cast.Type, render(cast.Operand)),
        IrConversionExpression conversion => $"(({Type(conversion.Type)}){render(conversion.Operand)})",
        IrBinaryExpression binary when binary.Left.Type != IrType.String => Arithmetic(binary, render),
        IrBinaryExpression comparison => $"({_text.StringComparison(comparison.Operation, render(comparison.Left), render(comparison.Right))})",
        _ => throw new NotSupportedException($"Unsupported expression '{expression.GetType().Name}'.")
    };

    private string Arithmetic(IrBinaryExpression arithmetic, Func<IrExpression, string> render)
    {
        IrType type = arithmetic.Left.Type;
        string expression = $"({render(arithmetic.Left)} {CStyleOperators.Symbol(arithmetic.Operation)} {render(arithmetic.Right)})";
        bool narrow = type is { IsIntegral: true, BitWidth: < 32 };
        if (narrow)
            expression = $"(({Type(type)}){expression})";

        return expression;
    }
}